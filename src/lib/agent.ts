export const DEFAULT_MODE: ModeId = "assist";

export function getMode(id: ModeId): Mode {
  return MODES.find((m) => m.id === id) ?? MODES[0];
}

export function buildSystemPrompt(modeId: ModeId): string {
  const mode = getMode(modeId);
  const header =
    mode.id === "assist"
      ? `## 현재 모드: 통합 비서
요청이 어떤 업무인지 스스로 판단해 처리합니다. 아래 업무별 규칙을 상황에 맞게 적용하세요.`
      : `## 현재 모드: ${mode.label}
사용자는 이 업무를 요청하고 있습니다. 아래 규칙을 지키세요.`;

  return `${BASE_PERSONA}

${header}

${mode.rules}`;
}

